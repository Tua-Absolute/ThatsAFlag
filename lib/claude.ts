/**
 * The two checks that call Claude:
 *  - scoreAiLikelihood: Claude reads each passage and estimates how likely it
 *    is to be AI-generated, with the signals it relied on.
 *  - searchWeb: Claude runs web searches for the paper's most distinctive
 *    sentences; we keep the result URLs and do the actual matching ourselves
 *    (see plagiarism.ts), so a flag always rests on text we can show.
 */
import Anthropic from "@anthropic-ai/sdk";
import { betaZodOutputFormat } from "@anthropic-ai/sdk/helpers/beta/zod";
import { z } from "zod";
import type { Span } from "./text";

export const DEFAULT_MODEL = "claude-opus-5-5";

export function getClient(): Anthropic | null {
  return process.env.ANTHROPIC_API_KEY ? new Anthropic() : null;
}

export function modelName(): string {
  return process.env.CLAUDE_MODEL?.trim() || DEFAULT_MODEL;
}

// Server-side refusal fallback is available for Opus/Sonnet 5.5-class models on the Claude API.
const fallbackOptions = (model: string) =>
  /^claude-(opus-5|sonnet-5-5|fable-5)/.test(model)
    ? { betas: ["server-side-fallback-2026-07-01"], fallbacks: "default" as const }
    : {};

const AiScores = z.object({
  passages: z.array(
    z.object({
      index: z.number().int(),
      ai_probability: z.number(),
      signals: z.array(z.string()),
    }),
  ),
});

const AI_SYSTEM = `You help instructors review undergraduate papers. For each numbered passage, estimate the probability (0 to 1) that it was generated by an AI language model rather than written by the student.

Ground every estimate in concrete, observable signals, for example: generic or formulaic phrasing, stock transitions ("Furthermore", "It is important to note"), balanced "not only... but also" constructions, summaries that restate without adding anything, vague claims with no specific detail, a sudden shift in voice or sophistication compared with the rest of the paper, or confident fabricated-sounding specifics. Also weigh signals of human writing: personal anecdotes, specific local detail, uneven rhythm, natural errors, a consistent student voice.

Be calibrated and conservative. Formal or polished writing alone is not evidence of AI, and neither is writing by a non-native English speaker. Only go above 0.5 when several independent signals point the same way. List the 1-4 strongest signals you used for each passage as short phrases, quoting a few words from the passage where useful.`;

export async function scoreAiLikelihood(client: Anthropic, model: string, passages: Span[]) {
  const numbered = passages.map((p, i) => `[${i}]\n${p.text}`).join("\n\n");
  const response = await client.beta.messages.parse({
    model,
    max_tokens: 16000,
    output_config: { effort: "medium", format: betaZodOutputFormat(AiScores) },
    system: AI_SYSTEM,
    messages: [{ role: "user", content: `Passages from one student paper, in order:\n\n${numbered}` }],
    ...fallbackOptions(model),
  });
  if (response.stop_reason === "refusal") throw new Error("Claude declined to score this paper.");
  const parsed = response.parsed_output;
  if (!parsed) throw new Error("Claude's AI-likelihood answer could not be read.");
  return parsed.passages.filter((p) => p.index >= 0 && p.index < passages.length);
}

export interface SearchHit {
  url: string;
  title?: string;
}

/** Runs one web search per sentence and returns the distinct result URLs. */
export async function searchWeb(client: Anthropic, model: string, queries: string[]): Promise<SearchHit[]> {
  if (!queries.length) return [];
  // Dynamic-filtering web search needs an Opus/Sonnet 4.6+ model; others get the basic tool.
  const tool = /opus|sonnet|fable/.test(model)
    ? { type: "web_search_20260209" as const, name: "web_search" as const, max_uses: queries.length + 2 }
    : { type: "web_search_20250305" as const, name: "web_search" as const, max_uses: queries.length + 2 };
  const messages: Anthropic.Beta.BetaMessageParam[] = [
    {
      role: "user",
      content:
        "I'm checking a student paper for text copied from the web. For each sentence below, run one web search using its most distinctive 8-15 word phrase in double quotes. Don't summarize the results; when all searches are done just reply \"done\".\n\n" +
        queries.map((q, i) => `${i + 1}. ${q}`).join("\n"),
    },
  ];
  const hits = new Map<string, SearchHit>();
  for (let round = 0; round < 4; round++) {
    const response = await client.beta.messages.create({
      model,
      max_tokens: 16000,
      output_config: { effort: "low" },
      tools: [tool],
      messages,
      ...fallbackOptions(model),
    });
    for (const block of response.content) {
      if (block.type === "web_search_tool_result" && Array.isArray(block.content)) {
        for (const r of block.content) if (!hits.has(r.url)) hits.set(r.url, { url: r.url, title: r.title });
      }
    }
    if (response.stop_reason !== "pause_turn") break;
    // Long server-tool turns pause; send the turn back so the server resumes it.
    messages.push({ role: "assistant", content: response.content });
  }
  return [...hits.values()];
}
